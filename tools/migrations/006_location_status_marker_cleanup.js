'use strict';
// Чистка старого маркер-формата «Статус» ([Город] Тип[ — Заметка]) под новый
// чистый формат (Тип), введённый техспекой «Статус заменяет Зону» (2026-08-06).
// Заметка при чистке ОТБРАСЫВАЕТСЯ — она уже дублируется в city.md
// («Отмеченные локации»), карточка локации хранить её больше не должна
// (см. §4 техспеки status-replaces-zone-techspec.md).
//
// Найдено ролью «Системный аналитик» при подготовке фикс-плана по отчёту QA
// (2026-08-06) — grep по всем cities/*/locations/ на момент написания нашёл
// ровно один непереехавший случай (cities/paris/locations/opera/opera_garne),
// но миграция общая, не точечная под этот файл.
//
// Идемпотентна: карточка без «[Город]» в значении «Статус» уже мигрирована
// или никогда не использовала маркер-формат — test() вернёт false.

const { CITY_LOCATION_TYPES } = require('../../web/lib/significant_places');

const TYPES_RE = CITY_LOCATION_TYPES.map(t => t.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|');
const STATUS_ROW_RE = new RegExp(
  `(\\|\\s*\\*\\*Статус\\*\\*\\s*\\|\\s*)\\[Город\\]\\s*(${TYPES_RE})(?:\\s+—\\s+[^|]*)?\\s*(\\|)`
);

module.exports = {
  description: 'чистка маркер-формата «Статус» ([Город] Тип — Заметка → Тип), 2026-08-06',
  test(text) { return STATUS_ROW_RE.test(text); },
  migrate(text) { return text.replace(STATUS_ROW_RE, '$1$2 $3'); },
};
