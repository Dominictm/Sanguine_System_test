'use strict';
// Бэкофилл «Опасность» — план 2026-08-02-city-creation-restructure-techspec.md §15.
// §13.1 развёл «Опасность» на собственное инлайн-поле карточки локации, отдельное
// от «Зоны» (zoneDangerLevel() теперь читает **Опасность:**, а не парсит эмодзи
// из текста «Зоны», как раньше) — но существующие карточки, у которых цветовой
// уровень (🟢/🟡/🔴) жил внутри «Зоны», без этой миграции молча теряют бейдж
// «Уровень опасности» в детальной модалке (`dLvl !== 'unknown'`).
//
// Найдено ролью «Тестировщик» при глубоком тестировании реализации §8-14; контракт
// (test/migrate ниже) дословно прогнан против cities/paris и cities/balmont перед
// фиксацией в техспеке — 23 из 28 карточек локаций содержат цветовой эмодзи в «Зоне»
// (остальные 5 используют маркеры вроде «🏛️ Элизиум»/«🔵 Вентру» без цветового
// уровня — для них бейдж не отображался и до этой правки, не наш случай).
//
// Идемпотентна: карточка с уже существующим «**Опасность:**» пропускается.

function _extractDangerEmoji(zoneVal) {
  if (zoneVal.includes('🟢')) return '🟢';
  if (zoneVal.includes('🟡')) return '🟡';
  if (zoneVal.includes('🔴')) return '🔴';
  return null;
}

module.exports = {
  description: 'бэкофилл **Опасность:** из эмодзи, ранее жившего внутри **Зона:** (2026-08-02, §15)',
  test(text) {
    if (/\*\*Опасность:\*\*/.test(text)) return false; // уже есть — идемпотентность
    const m = text.match(/\*\*Зона:\*\*\s*([^|\n]+)/);
    return !!(m && _extractDangerEmoji(m[1]));
  },
  migrate(text) {
    const m = text.match(/\*\*Зона:\*\*\s*([^|\n]+)/);
    const emoji = _extractDangerEmoji(m[1]);
    // Два реальных формата карточки на диске (проверено прогоном по обоим городам):
    // (1) стандартный pipe-delimited формат _locCardTemplate — новое поле вставляется
    // между «Зона» и следующим «|»; (2) более старый «одна метаданные-строка на
    // буллет», без «|» вообще (пример — cities/balmont/locations/podzemnyy_dok/…) —
    // добавляем отдельным буллетом сразу после строки «Зона», тем же стилем.
    if (/\*\*Зона:\*\*\s*[^|\n]+\|/.test(text)) {
      return text.replace(
        /(\*\*Зона:\*\*\s*[^|\n]+)(\|)/,
        `$1| **Опасность:** ${emoji} $2`
      );
    }
    return text.replace(
      /(\*\*Зона:\*\*\s*[^\n]+)(\n)/,
      `$1\n- **Опасность:** ${emoji}$2`
    );
  },
};
