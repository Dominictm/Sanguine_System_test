// (оборотни/маги/охотники). НЕ трогает fairies (у них «Титул» — другое поле, титул при
// Дворе) и НЕ трогает орфанный легаси-лейбл «Парижская иерархия» (не входит в контракт
// EDITABLE_FIELD_MAP, оставлен как read-only фоллбэк — см. техспеку §A2.3).
module.exports = {
  description: 'Переименование md-лейбла «Иерархия в городе» → «Титул в городе» (вампиры/смертные/generic)',
  test(text)    { return /^- \*\*Иерархия в городе:\*\*/m.test(text); },
  migrate(text) { return text.replace(/^- \*\*Иерархия в городе:\*\*/gm, '- **Титул в городе:**'); },
};
